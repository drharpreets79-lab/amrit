/**
 * Equalising the alert budget before anything is compared.
 *
 * This is the piece the whole benchmark rests on, and the reason Phase 33 exists as its own
 * phase rather than as a script at the end of Phase 31.
 *
 * Comparing detectors at their default thresholds compares tuning. AMRIT's scan alerts at a
 * recurrence interval of 365 days; a three-sigma EWMA chart alerts about once in 370 periods
 * *per series*, and Phase 30 measured what that means in practice — more than fifty signals on
 * a corpus with no outbreak in it, because 241 series were charted independently. Set those
 * two side by side at their own defaults and the chart looks vastly more sensitive and vastly
 * less specific, and neither number says anything about the methods.
 *
 * So every detector is first calibrated on **null replicates** — corpora generated by the same
 * simulator with no outbreak seeded at all — to the threshold on its own ranking statistic that
 * produces a chosen number of alerts per site-year. Only then is it run against the seeded
 * cells. Every detector is then spending the same alert budget, which is the budget an
 * infection-prevention team actually has: a fixed number of investigations per year.
 *
 * ## How the threshold is chosen
 *
 * Pool every signal from every null replicate, sort by evidence descending, and take the
 * `floor(rate * siteYears)`-th value as the threshold. A signal is alerted when its evidence is
 * **strictly greater** than the threshold, so the budget is an upper bound rather than a target
 * hit from below.
 *
 * Two boundary cases, both of which occur:
 *
 * * **Fewer null signals than the budget allows.** The detector is already quieter than the
 *   budget and no threshold is needed; `-Infinity` is returned and every signal is alerted.
 *   Its measured false-alert rate is then reported as what it is, below target, rather than
 *   being inflated to meet it.
 * * **A tie across the threshold.** Ranking statistics tie — this is why the scan family is
 *   ranked by log-likelihood ratio rather than by a recurrence interval capped at
 *   `permutations + 1`, where ties are the norm. The threshold takes the tied value itself,
 *   so a tie spends *less* than the budget rather than more. Reported in `tiedAtThreshold` so a
 *   detector that cannot reach its budget because of ties is visible rather than silently
 *   penalised.
 */

import type { DetectorSignal } from '../detection/registry'
import { evidenceOf } from './ranking'

export interface CalibrationInput {
  /** Signals from the null replicates, from one detector. */
  nullSignals: readonly DetectorSignal[]
  /** Site-years the null replicates cover. Sites x days / 365.25, summed over replicates. */
  siteYears: number
  /** Target alerts per site-year. The plan's default is 1. */
  targetRate: number
  /** Null cells the signals came from, so the reporting cap can be checked against the budget. */
  nullCells?: number
  /** Signals per cell a detector will return. 50 across this codebase. */
  perCellCap?: number
}

export interface Calibration {
  /** Alert when evidence is strictly greater than this. `-Infinity` alerts on everything. */
  threshold: number
  targetRate: number
  siteYears: number
  /** Alerts the threshold actually produces on the null replicates. */
  nullAlerts: number
  /** Measured rate at the chosen threshold. At or below target by construction. */
  achievedRate: number
  /** Null signals available. Below the budget means the detector is quieter than required. */
  nullSignals: number
  /** True when the budget could not be spent exactly because the statistic tied. */
  tiedAtThreshold: boolean
  /** Set when the detector produced fewer null signals than the budget allows. */
  belowBudget: boolean
  /**
   * Signals per cell each detector is willing to return.
   *
   * The detectors cap their reported signals at 50, so `nullSignals` is a count *after* that
   * cap and is a lower bound on what the null corpus actually produced — Phase 30 measured the
   * EWMA chart finding several hundred on a single corpus. The **threshold is unaffected**,
   * because the cap keeps the strongest signals and the budget is far below it, and
   * `calibrate` refuses to run when that stops being true.
   */
  perCellCap: number
}

export const SIGNAL_CAP_PER_CELL = 50

export function calibrate(input: CalibrationInput): Calibration {
  const siteYears = Math.max(1e-9, input.siteYears)
  const targetRate = Math.max(0, input.targetRate)
  const perCellCap = input.perCellCap ?? SIGNAL_CAP_PER_CELL
  // The threshold is the budget-th largest null value, and each cell contributes only its
  // strongest `perCellCap`. That is safe while the budget is below the cap and silently wrong
  // above it, so it is checked rather than assumed.
  const retained = perCellCap * Math.max(1, input.nullCells ?? 1)
  if (Math.floor(targetRate * siteYears) >= retained) {
    throw new Error(`An alert budget of ${Math.floor(targetRate * siteYears)} exceeds the `
      + `${retained} strongest null signals the detectors will report (${perCellCap} per cell across `
      + `${input.nullCells ?? 1} cells). The calibrated threshold would be set from a truncated null `
      + 'distribution. Lower the target rate, or add null replicates.')
  }
  const evidence = input.nullSignals
    .map((signal) => evidenceOf(signal))
    .filter((value): value is number => value !== null && Number.isFinite(value))
    .sort((left, right) => right - left)

  const budget = Math.floor(targetRate * siteYears)
  if (evidence.length === 0 || budget >= evidence.length) {
    return {
      threshold: Number.NEGATIVE_INFINITY,
      targetRate,
      siteYears,
      nullAlerts: evidence.length,
      achievedRate: evidence.length / siteYears,
      nullSignals: evidence.length,
      tiedAtThreshold: false,
      belowBudget: true,
      perCellCap
    }
  }

  // The budget-th largest value. Alerting strictly above it admits at most `budget` signals,
  // and fewer when values tie at it.
  const threshold = evidence[budget] as number
  const nullAlerts = evidence.filter((value) => value > threshold).length
  return {
    threshold,
    targetRate,
    siteYears,
    nullAlerts,
    achievedRate: nullAlerts / siteYears,
    nullSignals: evidence.length,
    tiedAtThreshold: nullAlerts < budget,
    belowBudget: false,
    perCellCap
  }
}

/** Signals a calibration admits. */
export function alerted(
  signals: readonly DetectorSignal[], calibration: Calibration
): DetectorSignal[] {
  return signals.filter((signal) => {
    const evidence = evidenceOf(signal)
    return evidence !== null && evidence > calibration.threshold
  })
}

/**
 * Site-years a set of corpora covers.
 *
 * The denominator of every false-alert rate in this harness, so it is computed once here and
 * not re-derived per detector. A "site-year" is one reporting site observed for one year;
 * a 730-day corpus over four sites is eight site-years, and a rate of one alert per site-year
 * means eight alerts across it.
 */
export function siteYearsOf(cells: readonly { sites: number; windowDays: number }[]): number {
  return cells.reduce((sum, cell) => sum + (cell.sites * cell.windowDays) / 365.25, 0)
}
